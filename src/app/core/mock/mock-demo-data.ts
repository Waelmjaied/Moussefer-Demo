// Helper: returns an ISO datetime N days from now at a fixed hour,
// so demo dates always look "upcoming" regardless of when it's viewed.
function inDays(days: number, hour: number = 8): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
}

